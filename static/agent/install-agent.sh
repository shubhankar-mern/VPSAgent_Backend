#!/usr/bin/env bash
set -Eeuo pipefail

# VPS Autopilot Linux agent installer.
# The backend host serves this script, the architecture-specific binaries,
# and SHA256SUMS from /downloads/agent/.

readonly INSTALL_DIR="/usr/local/bin"
readonly CONFIG_DIR="/etc/vps-agent"
readonly CONFIG_FILE="${CONFIG_DIR}/config.json"
readonly SERVICE_FILE="/etc/systemd/system/vps-agent.service"
readonly SERVICE_NAME="vps-agent"
readonly METRICS_PATH="/api/agent/metrics"
readonly AGENT_INTERVAL_SECONDS="15"
readonly AGENT_TIMEOUT_SECONDS="10"
readonly AGENT_MAX_PROCESSES="10"

API_URL=""

log() { printf '\n[vps-agent] %s\n' "$*"; }
fail() { printf '\n[vps-agent] ERROR: %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<'USAGE'
VPS Autopilot agent installer

Usage:
  sudo bash install-agent.sh --api-url https://api.yourdomain.com

Options:
  --api-url URL   Base URL of your VPS Autopilot backend (HTTPS required)
  -h, --help      Show this help

The installer securely prompts for the one-time agent token. Do not pass the
agent token as a command-line argument.
USAGE
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --api-url)
      [[ $# -ge 2 ]] || fail "--api-url requires a value."
      API_URL="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      fail "Unknown argument: $1 (use --help for usage)."
      ;;
  esac
done

[[ "$(uname -s)" == "Linux" ]] || fail "This installer supports Linux only."
[[ "${EUID:-$(id -u)}" -eq 0 ]] || fail "Run as root: sudo bash install-agent.sh --api-url https://api.yourdomain.com"
command -v systemctl >/dev/null 2>&1 || fail "systemd/systemctl was not found. This installer requires a systemd-based Linux distribution."

if [[ -z "$API_URL" ]]; then
  [[ -r /dev/tty ]] || fail "Backend URL required. Pass --api-url https://api.yourdomain.com"
  printf 'Backend API base URL (example: https://api.yourdomain.com): ' > /dev/tty
  IFS= read -r API_URL < /dev/tty
fi

# Restrict URL characters and require HTTPS so the bearer token is never sent
# over cleartext HTTP. The backend API and /downloads/agent assets share origin.
if [[ ! "$API_URL" =~ ^https://[A-Za-z0-9][A-Za-z0-9.-]*(:[0-9]{1,5})?$ ]]; then
  fail "Invalid backend URL. Use an HTTPS origin only, e.g. https://api.yourdomain.com (no trailing slash or path)."
fi
API_URL="${API_URL%/}"
DOWNLOAD_BASE_URL="${API_URL}/downloads/agent"

case "$(uname -m)" in
  x86_64|amd64)
    ARCH="amd64"
    ;;
  aarch64|arm64)
    ARCH="arm64"
    ;;
  *)
    fail "Unsupported CPU architecture: $(uname -m). Supported architectures: x86_64/amd64 and aarch64/arm64."
    ;;
esac

BINARY_NAME="vps-agent-linux-${ARCH}"

if [[ ! -r /dev/tty ]]; then
  fail "An interactive terminal is required to enter the one-time agent token securely."
fi

printf '\nVPS Autopilot server registration token: ' > /dev/tty
IFS= read -r -s AGENT_TOKEN < /dev/tty
printf '\n' > /dev/tty

# Tokens generated by the backend are 32-byte base64url strings. The wider
# length range leaves room for compatible future token formats.
if [[ ! "$AGENT_TOKEN" =~ ^[A-Za-z0-9_-]{20,100}$ ]]; then
  unset AGENT_TOKEN
  fail "Token format is invalid. Copy the one-time agent token from the dashboard and try again."
fi

SERVER_NAME="$(hostname -s 2>/dev/null || hostname 2>/dev/null || printf 'linux-server')"
SERVER_NAME="$(printf '%s' "$SERVER_NAME" | tr -cd 'A-Za-z0-9._-')"
[[ -n "$SERVER_NAME" ]] || SERVER_NAME="linux-server"

TMP_DIR="$(mktemp -d)"
cleanup() {
  unset AGENT_TOKEN 2>/dev/null || true
  rm -rf "$TMP_DIR"
}
trap cleanup EXIT

fetch() {
  local url="$1"
  local destination="$2"
  if command -v curl >/dev/null 2>&1; then
    curl --fail --silent --show-error --location --retry 3 --retry-delay 1 "$url" --output "$destination"
  elif command -v wget >/dev/null 2>&1; then
    wget --quiet --tries=3 --output-document="$destination" "$url"
  else
    fail "Neither curl nor wget is installed. Install curl and run this installer again."
  fi
}

log "Detected Linux ${ARCH}. Downloading ${BINARY_NAME}..."
fetch "${DOWNLOAD_BASE_URL}/${BINARY_NAME}" "${TMP_DIR}/${BINARY_NAME}"
fetch "${DOWNLOAD_BASE_URL}/SHA256SUMS" "${TMP_DIR}/SHA256SUMS"

command -v sha256sum >/dev/null 2>&1 || fail "sha256sum is required to verify the agent download."
EXPECTED_SHA="$(awk -v file="$BINARY_NAME" '$2 == file { print $1; exit }' "${TMP_DIR}/SHA256SUMS")"
[[ "$EXPECTED_SHA" =~ ^[a-fA-F0-9]{64}$ ]] || fail "Could not find a valid SHA-256 checksum for ${BINARY_NAME}."
ACTUAL_SHA="$(sha256sum "${TMP_DIR}/${BINARY_NAME}" | awk '{print $1}')"
[[ "$ACTUAL_SHA" == "$EXPECTED_SHA" ]] || fail "Agent binary checksum verification failed. Do not run this binary."

log "Checksum verified. Installing agent binary..."
install -d -m 755 "$INSTALL_DIR"
install -m 755 "${TMP_DIR}/${BINARY_NAME}" "${INSTALL_DIR}/vps-agent"

log "Writing protected agent configuration..."
install -d -m 700 "$CONFIG_DIR"
cat > "${TMP_DIR}/config.json" <<CONFIG
{
  "apiUrl": "${API_URL}",
  "metricsPath": "${METRICS_PATH}",
  "agentToken": "${AGENT_TOKEN}",
  "serverName": "${SERVER_NAME}",
  "intervalSeconds": ${AGENT_INTERVAL_SECONDS},
  "timeoutSeconds": ${AGENT_TIMEOUT_SECONDS},
  "maxProcesses": ${AGENT_MAX_PROCESSES}
}
CONFIG
chmod 600 "${TMP_DIR}/config.json"
install -o root -g root -m 600 "${TMP_DIR}/config.json" "$CONFIG_FILE"
unset AGENT_TOKEN

log "Installing systemd service..."
cat > "${TMP_DIR}/${SERVICE_NAME}.service" <<'SERVICE'
[Unit]
Description=VPS Autopilot Monitoring Agent
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=root
Group=root
Environment=VPS_AGENT_CONFIG=/etc/vps-agent/config.json
ExecStart=/usr/local/bin/vps-agent --config /etc/vps-agent/config.json
Restart=on-failure
RestartSec=5
RestartPreventExitStatus=78

NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
ProtectHome=true
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true
RestrictSUIDSGID=true
LockPersonality=true
MemoryDenyWriteExecute=true
RestrictRealtime=true
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6

[Install]
WantedBy=multi-user.target
SERVICE
install -o root -g root -m 644 "${TMP_DIR}/${SERVICE_NAME}.service" "$SERVICE_FILE"

systemctl daemon-reload
systemctl enable "$SERVICE_NAME" >/dev/null
systemctl restart "$SERVICE_NAME"

sleep 2
if systemctl is-active --quiet "$SERVICE_NAME"; then
  log "Installation complete. Agent service is running."
  systemctl --no-pager --full status "$SERVICE_NAME" || true
  cat <<'NEXT'

Useful commands:
  Check status:  sudo systemctl status vps-agent
  View logs:     sudo journalctl -u vps-agent -f
  Restart:       sudo systemctl restart vps-agent
  Stop:          sudo systemctl stop vps-agent
  Uninstall:     sudo systemctl disable --now vps-agent
                 sudo rm -f /etc/systemd/system/vps-agent.service
                 sudo rm -f /usr/local/bin/vps-agent
                 sudo rm -rf /etc/vps-agent
                 sudo systemctl daemon-reload

The agent sends its first metrics report immediately, then every 15 seconds.
NEXT
else
  printf '\n[vps-agent] The service did not remain active. Recent logs:\n' >&2
  journalctl -u "$SERVICE_NAME" -n 40 --no-pager >&2 || true
  fail "Installation completed, but the agent service is not running. Check the logs above. A 401/403 usually means the token is invalid, rotated, or revoked."
fi
